#!/usr/bin/env bash
# pdf-extract skill 安装器（**零外部仓库依赖**——不 clone 任何 GitHub 仓）
# 1. 探测/安装 miniforge
# 2. 创建 conda env
# 3. pip install -e <skill_dir>（装 paper_extract 包 + 拉 PyPI 依赖）
# 4. 预下载模型从 HuggingFace
# 5. 写 config
set -euo pipefail

ENV_NAME="${PAPER_EXTRACT_ENV_NAME:-pdf-extract-kit-1.0}"
SKILL_DIR="$(cd "$(dirname "$0")/.." && pwd)"

# 1. 找 conda
if ! command -v conda >/dev/null 2>&1 && [[ ! -x "$HOME/miniforge3/bin/conda" ]]; then
    echo "[1/5] miniforge 未安装，brew 安装（cask） ..."
    if ! command -v brew >/dev/null 2>&1; then
        echo "ERROR: 需要 brew 或手动安装 miniforge/miniconda 后再跑 setup.sh" >&2
        exit 1
    fi
    brew install --cask miniforge
fi
CONDA_BASE="$(conda info --base 2>/dev/null || echo "$HOME/miniforge3")"
CONDA="$CONDA_BASE/bin/conda"

# 2. 创建 env
echo "[2/5] 创建 conda env: $ENV_NAME (Python 3.10) ..."
"$CONDA" create -n "$ENV_NAME" python=3.10 -y
"$CONDA" config --env --set channels https://mirrors.tuna.tsinghua.edu.cn/anaconda/cloud/conda-forge
"$CONDA" config --env --set ssl_verify false
ENV_PY="$CONDA_BASE/envs/$ENV_NAME/bin/python"

# 3. pip install -e skill（自带 pyproject.toml；所有依赖走 PyPI，无 GitHub clone）
echo "[3/5] pip install -e $SKILL_DIR ..."
"$ENV_PY" -m pip install --retries 5 \
    --index-url https://pypi.tuna.tsinghua.edu.cn/simple \
    -e "$SKILL_DIR"

# 4. 预下载模型到 ~/.cache/paper-extract/models/（huggingface_hub snapshot_download）
echo "[4/5] 预下载 ~800 MB 模型到 ~/.cache/paper-extract/models/ ..."
"$ENV_PY" -c "
from paper_extract import models
print(models.get_layout_model_path())
print(models.get_formula_det_model_path())
print(models.get_formula_rec_model_dir())
print(models.get_ocr_det_model_dir())
print(models.get_ocr_rec_model_dir())
print('models ready')
"

# 5. 写 config
echo "[5/5] 写 config → ~/.config/pdf-extract/config.sh"
mkdir -p "$HOME/.config/pdf-extract"
cat > "$HOME/.config/pdf-extract/config.sh" <<EOF
# pdf-extract skill config (generated by setup.sh)
export PAPER_EXTRACT_ENV="$CONDA_BASE/envs/$ENV_NAME"
export PAPER_EXTRACT_PY="$ENV_PY"
EOF

cat <<MSG

✓ 安装完成（零 GitHub clone，全部走 PyPI + HuggingFace）

下一步：
  source ~/.config/pdf-extract/config.sh
  paper-extract <pdf> --out <dir>

可选：
  echo 'source ~/.config/pdf-extract/config.sh' >> ~/.zshrc   # 永久生效
  export PAPER_EXTRACT_CACHE=/shared/cache                    # 自定义模型缓存路径（多机共享）
MSG